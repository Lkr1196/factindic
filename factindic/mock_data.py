def make_docs(lang: str, n: int, split: str, seed: int = 0) -> list[dict]:
    spec = HI if lang == "hi" else BN
    rng = random.Random(f"{lang}-{split}-{seed}")
    docs = []
    for i in range(n):
        tpl, summ = spec["templates"][i % len(spec["templates"])]
        slots = {
            "city": rng.choice(spec["cities"]), "org": rng.choice(spec["orgs"]),
            "person": rng.choice(spec["people"]), "month": rng.choice(spec["months"]),
            "day": rng.randint(1, 28), "year": rng.choice([2021, 2022, 2023, 2024]),
            "n1": rng.choice([12, 45, 150, 230, 480, 1200]), "n2": rng.choice([3, 8, 15, 27, 64]),
            "n3": rng.choice([6, 9, 18, 350, 1250]), "pct": rng.choice([7, 12, 18, 25, 33]),
        }
        text = tpl.format(**slots)
        docs.append({"id": f"mock-{lang}-{split}-{i:04d}", "url": "", "title": "",
                     "summary": summ.format(**slots), "text": text})
    return docs
